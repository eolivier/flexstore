package org.flexstore.infra.spring.adapter.jpa

import jakarta.persistence.EntityManager
import org.assertj.core.api.Assertions.assertThat
import org.assertj.core.api.Assertions.within
import org.flexstore.domain.product.*
import org.flexstore.domain.sharedkernel.*
import org.junit.jupiter.api.AfterEach
import org.junit.jupiter.api.Test
import org.springframework.beans.factory.annotation.Autowired
import org.springframework.boot.test.context.SpringBootTest
import org.springframework.test.context.ActiveProfiles
import java.math.BigDecimal
import java.time.temporal.ChronoUnit

@ActiveProfiles("test")
@SpringBootTest
class EntityTimestampsIT {

    @Autowired
    private lateinit var entityManager: EntityManager

    @Autowired
    private lateinit var productRepository: ProductRepository

    @Autowired
    private lateinit var jpaProductRepository: JpaProductRepository

    private val lamp = DefinedProduct(
        ProductId.nextId(), Name("Timestamped lamp"), Description("Warm light"), Category.HOME, Price(Amount(BigDecimal(30)), Currency.EUR)
    )

    @AfterEach
    fun deleteLamp() {
        jpaProductRepository.deleteById(lamp.productId.id.value)
    }

    @Test
    fun `every entity should have a creation date and a last update date`() {
        // Act
        val entitiesWithoutDates = entityManager.metamodel.entities
            .filterNot { entity -> entity.attributes.map { it.name }.containsAll(listOf("createdAt", "updatedAt")) }
            .map { it.name }
        // Assert
        assertThat(entityManager.metamodel.entities).isNotEmpty
        assertThat(entitiesWithoutDates).isEmpty()
    }

    @Test
    fun `a new row should get its creation date as last update date, to the second`() {
        // Act
        productRepository.save(lamp)
        // Assert
        val stored = jpaProductRepository.findById(lamp.productId.id.value).orElseThrow()
        // Both dates are generated by Hibernate on insert, a few microseconds apart
        assertThat(stored.updatedAt).isCloseTo(stored.createdAt, within(1, ChronoUnit.SECONDS))
    }

    @Test
    fun `an update should keep the creation date and change the last update date`() {
        // Arrange
        productRepository.save(lamp)
        val created = jpaProductRepository.findById(lamp.productId.id.value).orElseThrow()
        // Act
        productRepository.save(lamp.copy(name = Name("Timestamped bedside lamp")))
        // Assert
        val updated = jpaProductRepository.findById(lamp.productId.id.value).orElseThrow()
        assertThat(updated.createdAt).isEqualTo(created.createdAt)
        assertThat(updated.updatedAt).isAfter(created.updatedAt)
    }
}
